import { useMemo, useState } from 'react'
import { useLocation } from 'react-router-dom'
import {
  CartesianGrid,
  Line,
  LineChart,
  PolarAngleAxis,
  PolarGrid,
  PolarRadiusAxis,
  Radar,
  RadarChart,
  ResponsiveContainer,
  Tooltip,
  XAxis,
  YAxis,
} from 'recharts'
import { BarChart3, Building2, Download, FileText, Gauge, TrendingUp, Users } from 'lucide-react'
import { insightsForSite, SITE_BY_ID, SITE_GEO, SITES, siteRiskSeries } from '../data/mockData'
import type { TimeRange } from '../types'
import { cn, downloadCsv, fmt, printRegion, RISK_STYLES } from '../lib/utils'
import { ChartTip, PageHeader, RiskBadge } from '../components/ui'
import { Sparkline } from '../components/Sparkline'
import { TimeRangeControl } from '../components/TimeRangeControl'

const COMPLIANCE_BY_ID = new Map(SITE_GEO.map((g) => [g.id, g]))

export default function SiteInsights() {
  const location = useLocation()
  const preselect = (location.state as { siteId?: string } | null)?.siteId
  const [siteId, setSiteId] = useState(preselect ?? 'SBG-01')
  const [range, setRange] = useState<TimeRange>('90d')

  const site = SITE_BY_ID.get(siteId) ?? SITES[0]
  const insight = useMemo(() => insightsForSite(siteId), [siteId])
  const compliance = COMPLIANCE_BY_ID.get(site.id)
  const riskSeries = useMemo(() => siteRiskSeries(siteId, range), [siteId, range])

  // Flat one-sheet export: KPIs, exposure profile, leading precursors, interventions.
  const exportRows = (): (string | number)[][] => [
    ['Risk score (0-100)', site.riskScore],
    ['Risk level', site.riskLevel],
    ['Site ID', site.id],
    ['City / region', `${site.city} · ${site.region}`],
    ['Headcount', site.headcount],
    ['Reports processed', site.reports],
    ['Open precursors', site.openPrecursors],
    ['Unmapped incidents', site.unmapped],
    ['Last audit', site.lastAudit],
    ...insight.radar.map((d) => [`Exposure — ${d.category}`, d.score] as (string | number)[]),
    ...insight.leading.map((d) => [`Precursor — ${d.name} (90d)`, d.value] as (string | number)[]),
    ...insight.riskTrend.map((d) => [`Risk trend — ${d.month}`, d.score] as (string | number)[]),
    ...site.interventions.map((iv, i) => [`Intervention ${i + 1}`, iv] as (string | number)[]),
  ]

  const exportCsv = () => {
    downloadCsv(`sifguard-${site.id}-${new Date().toISOString().slice(0, 10)}.csv`, ['Metric', 'Value'], exportRows())
  }

  const exportPdf = () => {
    const html = `
      <div class="eyebrow">SIFGuard · Site Safety One-Pager</div>
      <h1>${site.name}</h1>
      <div class="muted">${site.id} · ${site.city} · ${site.region} · last audit ${site.lastAudit}</div>
      <div class="kpis">
        <div class="kpi"><b>${site.riskScore}</b><span>Composite risk score</span></div>
        <div class="kpi"><b>${site.riskLevel}</b><span>Priority level</span></div>
        <div class="kpi"><b>${site.openPrecursors}</b><span>Open precursors</span></div>
        <div class="kpi"><b>${site.unmapped}</b><span>Unmapped incidents</span></div>
        <div class="kpi"><b>${site.headcount.toLocaleString('en-IN')}</b><span>Headcount</span></div>
      </div>
      <h2>LSR exposure profile</h2>
      <table><thead><tr><th>Life-Saving Rule category</th><th>Exposure</th></tr></thead><tbody>
        ${insight.radar.map((d) => `<tr><td>${d.category}</td><td>${d.score}/100</td></tr>`).join('')}
      </tbody></table>
      <h2>Leading precursors (90 days)</h2>
      <table><thead><tr><th>Precursor</th><th>Count</th></tr></thead><tbody>
        ${insight.leading.map((d) => `<tr><td>${d.name}</td><td>${d.value}</td></tr>`).join('')}
      </tbody></table>
      <h2>Risk trend (6 months)</h2>
      <table><thead><tr><th>Month</th><th>Score</th></tr></thead><tbody>
        ${insight.riskTrend.map((d) => `<tr><td>${d.month}</td><td>${d.score}</td></tr>`).join('')}
      </tbody></table>
      <h2>Recommended interventions</h2>
      <ul>${site.interventions.map((iv) => `<li>${iv}</li>`).join('')}</ul>
      <footer>Generated by SIFGuard from ${site.reports} processed safety reports · ${new Date().toLocaleString('en-IN')} · Evidence pack for ISO 45001 / Factories Act review</footer>`
    printRegion(html, `SIFGuard — ${site.name}`)
  }

  return (
    <div className="animate-fade-up space-y-6">
      <PageHeader
        icon={<BarChart3 className="h-5 w-5" />}
        eyebrow="Site Analytics"
        title="Site Insights"
        sub="Deep-dive analytics per industrial site — exposure profile, trend and leading precursors"
        right={
          <div className="flex items-center gap-2">
            <button className="btn-secondary" onClick={exportCsv} title={`Export ${site.name} metrics as CSV`}>
              <Download className="h-3.5 w-3.5" /> CSV
            </button>
            <button className="btn-secondary" onClick={exportPdf} title={`Print / save ${site.name} one-pager as PDF`}>
              <FileText className="h-3.5 w-3.5" /> PDF one-pager
            </button>
          </div>
        }
      />

      {/* Site selector chips */}
      <div className="flex flex-wrap gap-2">
        {SITES.map((s) => (
          <button
            key={s.id}
            onClick={() => setSiteId(s.id)}
            className={cn(
              'flex items-center gap-2 rounded-[var(--radius-control)] border px-3 py-2 text-left transition-all duration-150 hover:-translate-y-px hover:shadow-rest',
              siteId === s.id
                ? 'border-navy-900 bg-navy-900 text-white shadow-rest'
                : 'border-navy-200 bg-white text-navy-700 hover:border-navy-300'
            )}
          >
            <span className={cn('h-2 w-2 rounded-full', RISK_STYLES[s.riskLevel].dot)} />
            <span className="text-[12.5px] font-semibold">{s.name}</span>
            <span className={cn('tnum text-[11px] font-bold', siteId === s.id ? 'text-gold-400' : 'text-navy-300')}>
              {s.riskScore}
            </span>
          </button>
        ))}
      </div>

      {/* Header stats */}
      <div className="grid grid-cols-1 gap-4 md:grid-cols-4">
        <div className="card p-5 md:col-span-2">
          <div className="flex items-center gap-3">
            <span className="flex h-11 w-11 items-center justify-center rounded-sm bg-navy-900 text-gold-500">
              <Building2 className="h-5.5 w-5.5" />
            </span>
            <div>
              <div className="flex items-center gap-2">
                <h2 className="text-base font-bold text-navy-900">{site.name}</h2>
                <RiskBadge level={site.riskLevel} />
              </div>
              <p className="text-[12px] text-navy-400">
                {site.id} · {site.city} · {site.region}
              </p>
            </div>
          </div>
          <div className="mt-4 grid grid-cols-2 gap-3 sm:grid-cols-4">
            <div>
              <div className="flex items-center gap-1 text-[11px] uppercase tracking-wide text-navy-400">
                <Users className="h-3 w-3" /> Headcount
              </div>
              <div className="tnum mt-1 text-lg font-bold text-navy-900">{fmt(site.headcount)}</div>
            </div>
            <div>
              <div className="text-[11px] uppercase tracking-wide text-navy-400">Reports</div>
              <div className="tnum mt-1 text-lg font-bold text-navy-900">{fmt(site.reports)}</div>
            </div>
            <div>
              <div className="text-[11px] uppercase tracking-wide text-navy-400">Last audit</div>
              <div className="tnum mt-1 text-lg font-bold text-navy-900">{site.lastAudit.slice(5)}</div>
            </div>
            <div title={compliance ? `${compliance.mapped} of ${compliance.total} incidents mapped to a Life-Saving Rule` : undefined}>
              <div className="flex items-center gap-1 text-[11px] uppercase tracking-wide text-navy-400">
                <Gauge className="h-3 w-3" /> LSR compliance
              </div>
              <div className="tnum mt-1 text-lg font-bold text-gold-700">
                {compliance ? `${compliance.compliance}%` : '—'}
              </div>
            </div>
          </div>
        </div>

        <div className="card flex items-center justify-between p-5 md:col-span-2">
          <div>
            <div className="text-[11px] font-semibold uppercase tracking-[0.1em] text-navy-400">
              10-month risk trajectory
            </div>
            <div className="mt-1.5 flex items-baseline gap-2">
              <span className="tnum text-3xl font-bold text-navy-900">{site.riskScore}</span>
              <span className="text-[12px] font-medium text-navy-400">/ 100 composite</span>
            </div>
            <p className="mt-1.5 text-[11.5px] text-navy-400">
              {site.riskScore >= 75
                ? 'Escalating — immediate intervention warranted'
                : site.riskScore >= 50
                  ? 'Elevated — monitor weekly'
                  : 'Stable — routine governance'}
            </p>
          </div>
          <Sparkline data={site.trend} stroke={RISK_STYLES[site.riskLevel].hex} w={150} h={48} className="!h-12 !w-[150px]" />
        </div>
      </div>

      {/* Charts */}
      <div className="grid grid-cols-1 gap-6 xl:grid-cols-5">
        {/* Radar */}
        <div className="card xl:col-span-2">
          <div className="card-header">
            <h2 className="card-title">LSR Exposure Profile</h2>
            <span className="text-[11px] text-navy-300">lower = safer</span>
          </div>
          <div className="h-80 p-4">
            <ResponsiveContainer width="100%" height="100%">
              <RadarChart data={insight.radar} outerRadius="72%">
                <PolarGrid stroke="#dce4f0" />
                <PolarAngleAxis dataKey="category" tick={{ fontSize: 10.5, fill: '#4a6a99' }} />
                <PolarRadiusAxis domain={[0, 100]} tick={false} axisLine={false} />
                <Radar
                  name="Exposure"
                  dataKey="score"
                  stroke="#0a1526"
                  fill="#efa93b"
                  fillOpacity={0.45}
                  strokeWidth={2}
                />
                <Tooltip content={<ChartTip />} />
              </RadarChart>
            </ResponsiveContainer>
          </div>
        </div>

        {/* Trend line */}
        <div className="card xl:col-span-3">
          <div className="card-header">
            <h2 className="card-title">
              <TrendingUp className="h-4 w-4 text-gold-600" /> Risk Score Trend
            </h2>
            <TimeRangeControl value={range} onChange={setRange} />
          </div>
          <div className="h-80 p-4 pr-6">
            <ResponsiveContainer width="100%" height="100%">
              <LineChart data={riskSeries} margin={{ top: 10, right: 8, left: -18, bottom: 0 }}>
                <CartesianGrid strokeDasharray="3 3" stroke="#dce4f0" vertical={false} />
                <XAxis
                  dataKey="label"
                  tick={{ fontSize: 11, fill: '#7c94b8' }}
                  axisLine={false}
                  tickLine={false}
                  interval="preserveStartEnd"
                  minTickGap={24}
                />
                <YAxis domain={[0, 100]} tick={{ fontSize: 11, fill: '#7c94b8' }} axisLine={false} tickLine={false} />
                <Tooltip content={<ChartTip />} />
                <Line
                  type="monotone"
                  dataKey="score"
                  name="Risk score"
                  stroke="#0a1526"
                  strokeWidth={2.4}
                  dot={{ r: 3.5, fill: '#efa93b', stroke: '#0a1526', strokeWidth: 1.5 }}
                  activeDot={{ r: 5 }}
                />
              </LineChart>
            </ResponsiveContainer>
          </div>
        </div>
      </div>

      {/* Leading precursors + interventions */}
      <div className="grid grid-cols-1 gap-6 xl:grid-cols-2">
        <div className="card">
          <div className="card-header">
            <h2 className="card-title">Leading Precursors</h2>
            <span className="text-[11px] text-navy-300">count in last 90 days</span>
          </div>
          <div className="space-y-3 p-5">
            {insight.leading.map((l, i) => {
              const max = Math.max(...insight.leading.map((x) => x.value))
              return (
                <div key={l.name} className="flex items-center gap-3">
                  <span className="tnum w-6 text-[12px] font-bold text-navy-300">{i + 1}.</span>
                  <span className="w-52 shrink-0 truncate text-[13px] text-navy-700">{l.name}</span>
                  <div className="h-2 flex-1 overflow-hidden rounded-full bg-navy-100">
                    <div
                      className={cn('h-full rounded-full', i === 0 ? 'bg-gold-500' : 'bg-navy-500')}
                      style={{ width: `${(l.value / max) * 100}%` }}
                    />
                  </div>
                  <span className="tnum w-7 text-right text-[13px] font-bold text-navy-900">{l.value}</span>
                </div>
              )
            })}
          </div>
        </div>

        <div className="card">
          <div className="card-header">
            <h2 className="card-title">Active Interventions</h2>
            <RiskBadge level={site.riskLevel} />
          </div>
          <div className="space-y-2.5 p-5">
            {site.interventions.map((iv, i) => (
              <div key={iv} className="flex items-start gap-3 rounded-sm border border-navy-100 bg-navy-50/50 p-3">
                <span className="mt-0.5 flex h-5 w-5 shrink-0 items-center justify-center rounded-sm bg-navy-900 text-[10.5px] font-bold text-gold-500">
                  {i + 1}
                </span>
                <p className="text-[13px] leading-relaxed text-navy-700">{iv}</p>
              </div>
            ))}
          </div>
          <div className="flex items-center justify-between border-t border-navy-100 px-5 py-3 text-[11.5px] text-navy-400">
            <span>Compliance evidence pack — ISO 45001 / Factories Act</span>
            <button className="link-quiet inline-flex items-center gap-1" onClick={exportPdf}>
              <FileText className="h-3.5 w-3.5" /> Generate one-pager
            </button>
          </div>
        </div>
      </div>
    </div>
  )
}
